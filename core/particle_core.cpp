static PyObject *py_templates_init(PyObject *, PyObject *args) {
    PyObject *schema, *userDir = nullptr;
    if (!PyArg_ParseTuple(args, "O!|O", &PyList_Type, &schema, &userDir)) return nullptr;
    trailpub::g_reg.schema.clear();
    for (Py_ssize_t i = 0; i < PyList_Size(schema); i++) {
        PyObject *f = PyList_GetItem(schema, i);
        if (!f || !PyDict_Check(f)) continue;
        PyObject *ok = PyDict_GetItemString(f, "key");
        PyObject *ot = PyDict_GetItemString(f, "type");
        if (!ok || !PyUnicode_Check(ok) || !ot || !PyUnicode_Check(ot)) continue;
        FieldSpec sp;
        const char *ks = PyUnicode_AsUTF8(ok), *ts = PyUnicode_AsUTF8(ot);
        if (!ks || !ts) continue;
        sp.key = ks;
        sp.type = ftype_of(ts);
        sp.lo = dget(f, "min", 0);
        sp.hi = dget(f, "max", 1);
        PyObject *items = PyDict_GetItemString(f, "items");
        if (items && PyList_Check(items))
            for (Py_ssize_t j = 0; j < PyList_Size(items); j++) {
                PyObject *o = PyList_GetItem(items, j);
                if (o && PyUnicode_Check(o)) {
                    const char *s = PyUnicode_AsUTF8(o);
                    if (s) sp.items.push_back(s);
                }
            }
        trailpub::g_reg.schema.push_back(sp);
    }
    if (userDir && PyUnicode_Check(userDir)) {
        const char *s = PyUnicode_AsUTF8(userDir);
        if (s) trailpub::g_reg.userDir = s;
    }
    return PyLong_FromSize_t(trailpub::g_reg.schema.size());
}

static PyObject *py_templates_register(PyObject *, PyObject *args) {
    const char *id;
    PyObject *data;
    int isUser = 0;
    if (!PyArg_ParseTuple(args, "sO!|p", &id, &PyDict_Type, &data, &isUser)) return nullptr;
    Template t;
    std::string warn;
    parse_template_doc(data, id, isUser != 0, t, warn);
    int at = trailpub::g_reg.index_of(id);
    if (at >= 0) trailpub::g_reg.items[(size_t)at] = t;
    else trailpub::g_reg.items.push_back(t);
    if (warn.empty()) Py_RETURN_NONE;
    return PyUnicode_FromString(warn.c_str());
}

static PyObject *py_templates_list(PyObject *, PyObject *args) {
    PyObject *a0 = nullptr, *a1 = nullptr, *a2 = nullptr, *a3 = nullptr, *a4 = nullptr;
    if (!PyArg_UnpackTuple(args, "templates_list", 0, 5, &a0, &a1, &a2, &a3, &a4)) return nullptr;
    auto cstr = [](PyObject *o) -> const char * {
        if (o && PyUnicode_Check(o)) {
            const char *s = PyUnicode_AsUTF8(o);
            return s ? s : "";
        }
        return "";
    };
    std::string q = lower_of(cstr(a1));
    std::string cat = lower_of(cstr(a0));
    std::string mode = lower_of(cstr(a2));
    std::string sort = lower_of(cstr(a3));
    if (sort.empty()) sort = "name";
    int favOnly = (a4 && PyObject_IsTrue(a4) > 0) ? 1 : 0;
    int modeBit = 0;
    if (mode == "2d") modeBit = 1;
    if (mode == "3d") modeBit = 2;
    struct Hit { int idx; int recent; };
    std::vector<Hit> hits;
    for (size_t i = 0; i < trailpub::g_reg.items.size(); i++) {
        const Template &t = trailpub::g_reg.items[i];
        if (!cat.empty() && cat != "all" && cat != "user" && t.category != cat) continue;
        if (cat == "user" && !t.user) continue;
        if (modeBit && !(t.modes & modeBit)) continue;
        if (favOnly) {
            bool f = false;
            for (auto &x : trailpub::g_reg.favs)
                if (x == t.id) { f = true; break; }
            if (!f) continue;
        }
        if (!trailpub::match_query(t, q)) continue;
        int rec = -1;
        for (size_t r = 0; r < trailpub::g_reg.recents.size(); r++)
            if (trailpub::g_reg.recents[r] == t.id) { rec = (int)r; break; }
        hits.push_back({(int)i, rec});
    }
    if (sort == "recent") {
        std::sort(hits.begin(), hits.end(), [](const Hit &a, const Hit &b) {
            if ((a.recent < 0) != (b.recent < 0)) return a.recent >= 0;
            return a.recent < b.recent;
        });
    } else {
        std::sort(hits.begin(), hits.end(), [](const Hit &a, const Hit &b) {
            return trailpub::g_reg.items[(size_t)a.idx].name <
                   trailpub::g_reg.items[(size_t)b.idx].name;
        });
    }
    PyObject *lst = PyList_New(hits.size());
    if (!lst) return nullptr;
    for (size_t i = 0; i < hits.size(); i++)
        PyList_SET_ITEM(lst, i, PyUnicode_FromString(
            trailpub::g_reg.items[(size_t)hits[i].idx].id.c_str()));
    return lst;
}

static PyObject *py_templates_info(PyObject *, PyObject *args) {
    const char *id;
    if (!PyArg_ParseTuple(args, "s", &id)) return nullptr;
    int at = trailpub::g_reg.index_of(id);
    if (at < 0) { PyErr_SetString(PyExc_KeyError, id); return nullptr; }
    return template_info_dict(trailpub::g_reg.items[(size_t)at]);
}

static PyObject *py_templates_apply(PyObject *, PyObject *args) {
    const char *id, *mode = "2d";
    PyObject *defaults, *current;
    if (!PyArg_ParseTuple(args, "ssO!O!", &id, &mode,
                          &PyDict_Type, &defaults,
                          &PyDict_Type, &current)) return nullptr;
    int at = trailpub::g_reg.index_of(id);
    if (at < 0) { PyErr_SetString(PyExc_KeyError, id); return nullptr; }
    const Template &t = trailpub::g_reg.items[(size_t)at];
    bool is3d = mode && !strcmp(mode, "3d");
    trailpub::Merged m;
    trailpub::merge_settings(trailpub::g_reg, t, is3d, defaults, m);
    PyObject *nd = PyDict_New();
    PyObject *ch = PyList_New(0);
    if (!nd || !ch) { Py_XDECREF(nd); Py_XDECREF(ch); return nullptr; }
    for (size_t i = 0; i < m.all.size(); i++) {
        const FieldSpec &sp = trailpub::g_reg.schema[i];
        PyObject *v = setting_to_py(sp, m.all[i]);
        if (!v) { Py_DECREF(nd); Py_DECREF(ch); return nullptr; }
        PyDict_SetItemString(nd, sp.key.c_str(), v);
        Py_DECREF(v);
        if (setting_differs(sp, m.all[i], current)) {
            PyObject *k = PyUnicode_FromString(sp.key.c_str());
            if (!k || PyList_Append(ch, k) < 0) {
                Py_XDECREF(k); Py_DECREF(nd); Py_DECREF(ch); return nullptr;
            }
            Py_DECREF(k);
        }
    }
    auto &rc = trailpub::g_reg.recents;
    rc.erase(std::remove(rc.begin(), rc.end(), t.id), rc.end());
    rc.insert(rc.begin(), t.id);
    if (rc.size() > 12) rc.pop_back();
    PyObject *r = PyTuple_New(2);
    if (!r) { Py_DECREF(nd); Py_DECREF(ch); return nullptr; }
    PyTuple_SET_ITEM(r, 0, nd);
    PyTuple_SET_ITEM(r, 1, ch);
    return r;
}

static PyObject *py_templates_thumbnail(PyObject *, PyObject *args) {
    const char *id;
    int w = 96, h = 48;
    if (!PyArg_ParseTuple(args, "s|ii", &id, &w, &h)) return nullptr;
    auto &reg = trailpub::g_reg;
    for (auto &b : reg.thumbs)
        if (b.id == id && b.w == w && b.h == h)
            return Py_BuildValue("(iiy#)", b.w, b.h, b.px.data(), (Py_ssize_t)b.px.size());
    if (reg.index_of(id) < 0) { PyErr_SetString(PyExc_KeyError, id); return nullptr; }
    std::vector<unsigned char> px((size_t)w * h * 4, 0);
    for (int y = 0; y < h; y++)
        for (int x = 0; x < w; x++) {
            double u = (x + 0.5) / w;
            double a = 255 * (1.0 - u);
            size_t o = ((size_t)y * w + x) * 4;
            px[o] = px[o + 1] = px[o + 2] = 255;
            px[o + 3] = (unsigned char)a;
        }
    trailpub::Registry::Blob b;
    b.id = id; b.w = w; b.h = h; b.px = px;
    reg.thumbs.push_back(b);
    const auto &bb = reg.thumbs.back();
    return Py_BuildValue("(iiy#)", bb.w, bb.h, bb.px.data(), (Py_ssize_t)bb.px.size());
}

static PyObject *py_templates_texture(PyObject *, PyObject *args) {
    const char *kind;
    int w = 64, h = 64;
    if (!PyArg_ParseTuple(args, "s|ii", &kind, &w, &h)) return nullptr;
    w = std::min(256, std::max(8, w));
    h = std::min(256, std::max(8, h));
    std::string key = std::string(kind ? kind : "glow");
    auto &reg = trailpub::g_reg;
    for (auto &b : reg.texcache)
        if (b.id == key && b.w == w && b.h == h)
            return Py_BuildValue("(iiy#)", b.w, b.h, b.px.data(), (Py_ssize_t)b.px.size());
    trailpub::Registry::Blob b;
    b.id = key; b.w = w; b.h = h;
    b.px = trailpub::proc_texture(key, w, h);
    reg.texcache.push_back(b);
    const auto &bb = reg.texcache.back();
    return Py_BuildValue("(iiy#)", bb.w, bb.h, bb.px.data(), (Py_ssize_t)bb.px.size());
}

static PyObject *py_templates_fav(PyObject *, PyObject *args) {
    const char *id;
    int on = 1;
    if (!PyArg_ParseTuple(args, "s|p", &id, &on)) return nullptr;
    auto &fv = trailpub::g_reg.favs;
    fv.erase(std::remove(fv.begin(), fv.end(), std::string(id)), fv.end());
    if (on) fv.push_back(id);
    Py_RETURN_NONE;
}

static PyObject *py_presets_save(PyObject *, PyObject *args) {
    const char *name;
    PyObject *settings, *meta = nullptr;
    if (!PyArg_ParseTuple(args, "sO!|O!", &name, &PyDict_Type, &settings,
                          &PyDict_Type, &meta)) return nullptr;
    std::string warn;
    std::vector<trailpub::Setting> vals;
    trailpub::validate_block(settings, trailpub::g_reg, vals, warn);
    if (!warn.empty()) {
        PyErr_SetString(PyExc_ValueError, warn.c_str());
        return nullptr;
    }
    std::string js = "{\n  \"id\": \"" + trailpub::json_esc(name) +
        "\",\n  \"name\": \"" + trailpub::json_esc(
            meta ? sget(meta, "name", name) : std::string(name)) +
        "\",\n  \"category\": \"" + trailpub::json_esc(
            meta ? sget(meta, "category", "user") : std::string("user")) +
        "\",\n  \"description\": \"" + trailpub::json_esc(
            meta ? sget(meta, "description", "") : std::string("")) +
        "\",\n  \"tags\": [\"user\"],\n  \"modes\": [\"2d\", \"3d\"],\n"
        "  \"texture\": null,\n  \"version\": 1,\n  \"settings\": {";
    bool first = true;
    char buf[64];
    for (auto &s : vals) {
        const FieldSpec &sp = trailpub::g_reg.schema[(size_t)s.spec];
        if (!first) js += ",";
        first = false;
        js += "\n    \"" + sp.key + "\": ";
        if (sp.type == FT_BOOL) js += (s.num != 0.0 ? "true" : "false");
        else if (sp.type == FT_INT) { snprintf(buf, sizeof buf, "%d", (int)s.num); js += buf; }
        else if (sp.type == FT_FLOAT) { snprintf(buf, sizeof buf, "%.6g", s.num); js += buf; }
        else if (sp.type == FT_COMBO || sp.type == FT_TEXT) js += "\"" + trailpub::json_esc(s.str) + "\"";
        else {
            js += "[";
            for (size_t i = 0; i < s.keys.x.size(); i++) {
                if (i) js += ", ";
                snprintf(buf, sizeof buf, "[%.6g, ", s.keys.x[i]);
                js += buf;
                if (s.keys.numeric) { snprintf(buf, sizeof buf, "%.6g", s.keys.ynum[i]); js += buf; }
                else js += "\"" + trailpub::json_esc(s.keys.ystr[i]) + "\"";
                js += ", \"" + std::string(MODESTR[s.keys.mode[i] % 3]) + "\"]";
            }
            js += "]";
        }
    }
    js += "\n  }\n}\n";
    std::string dir = trailpub::g_reg.userDir;
    if (dir.empty()) { PyErr_SetString(PyExc_RuntimeError, "user preset dir not set"); return nullptr; }
    std::string path = dir + "/" + name + ".json";
    FILE *f = fopen(path.c_str(), "wb");
    if (!f) { PyErr_SetString(PyExc_OSError, path.c_str()); return nullptr; }
    fwrite(js.data(), 1, js.size(), f);
    fclose(f);
    return PyUnicode_FromString(path.c_str());
}

static PyObject *py_presets_delete(PyObject *, PyObject *args) {
    const char *name;
    if (!PyArg_ParseTuple(args, "s", &name)) return nullptr;
    std::string dir = trailpub::g_reg.userDir;
    if (dir.empty()) { PyErr_SetString(PyExc_RuntimeError, "user preset dir not set"); return nullptr; }
    std::string path = dir + "/" + name + ".json";
    if (remove(path.c_str()) != 0) { PyErr_SetString(PyExc_OSError, path.c_str()); return nullptr; }
    int at = trailpub::g_reg.index_of(name);
    if (at >= 0 && trailpub::g_reg.items[(size_t)at].user)
        trailpub::g_reg.items.erase(trailpub::g_reg.items.begin() + at);
    Py_RETURN_NONE;
}

