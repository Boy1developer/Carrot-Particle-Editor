const char *MODESTR[3] = {"linear", "smooth", "constant"};

FieldType ftype_of(const char *s) {
    if (!strcmp(s, "bool")) return FT_BOOL;
    if (!strcmp(s, "int")) return FT_INT;
    if (!strcmp(s, "float")) return FT_FLOAT;
    if (!strcmp(s, "combo")) return FT_COMBO;
    if (!strcmp(s, "text") || !strcmp(s, "color") || !strcmp(s, "file")) return FT_TEXT;
    if (!strcmp(s, "curve")) return FT_CURVE;
    if (!strcmp(s, "gradient-color") || !strcmp(s, "gradient-alpha")) return FT_GRAD;
    return FT_TEXT;
}

PyObject *setting_to_py(const FieldSpec &sp, const Setting &s) {
    switch (sp.type) {
        case FT_BOOL: return PyBool_FromLong(s.num != 0.0);
        case FT_INT: return PyLong_FromLong((long)s.num);
        case FT_FLOAT: return PyFloat_FromDouble(s.num);
        case FT_COMBO:
        case FT_TEXT: return PyUnicode_FromString(s.str.c_str());
        case FT_CURVE:
        case FT_GRAD: {
            PyObject *lst = PyList_New(s.keys.x.size());
            if (!lst) return nullptr;
            for (size_t i = 0; i < s.keys.x.size(); i++) {
                PyObject *o = PyFloat_FromDouble(s.keys.x[i]);
                PyObject *y = s.keys.numeric
                    ? (PyObject *)PyFloat_FromDouble(s.keys.ynum[i])
                    : (PyObject *)PyUnicode_FromString(s.keys.ystr[i].c_str());
                PyObject *row = PyList_New(3);
                if (!row || !o || !y) {
                    Py_XDECREF(o); Py_XDECREF(y); Py_XDECREF(row);
                    Py_DECREF(lst);
                    return nullptr;
                }
                PyList_SET_ITEM(row, 0, o);
                PyList_SET_ITEM(row, 1, y);
                PyList_SET_ITEM(row, 2, PyUnicode_FromString(MODESTR[s.keys.mode[i] % 3]));
                PyList_SET_ITEM(lst, i, row);
            }
            return lst;
        }
    }
    Py_RETURN_NONE;
}

bool setting_differs(const FieldSpec &sp, const Setting &s, PyObject *cur) {
    PyObject *v = cur ? PyDict_GetItemString(cur, sp.key.c_str()) : nullptr;
    if (!v || v == Py_None) return true;
    switch (sp.type) {
        case FT_BOOL: {
            int b = PyObject_IsTrue(v);
            if (b < 0) { PyErr_Clear(); return true; }
            return (b != 0) != (s.num != 0.0);
        }
        case FT_INT: {
            long x = PyLong_AsLong(v);
            if (PyErr_Occurred()) { PyErr_Clear(); return true; }
            return x != (long)s.num;
        }
        case FT_FLOAT: {
            double x = PyFloat_AsDouble(v);
            if (PyErr_Occurred()) { PyErr_Clear(); return true; }
            return x != s.num;
        }
        case FT_COMBO:
        case FT_TEXT: {
            if (!PyUnicode_Check(v)) return true;
            const char *sv = PyUnicode_AsUTF8(v);
            return !sv || s.str != sv;
        }
        case FT_CURVE:
        case FT_GRAD: {
            if (!PyList_Check(v)) return true;
            if (PyList_Size(v) != (Py_ssize_t)s.keys.x.size()) return true;
            for (size_t i = 0; i < s.keys.x.size(); i++) {
                PyObject *k = PyList_GetItem(v, i);
                if (!k || !PyList_Check(k) || PyList_Size(k) < 2) return true;
                double x = PyFloat_AsDouble(PyList_GetItem(k, 0));
                if (PyErr_Occurred()) { PyErr_Clear(); return true; }
                if (x != s.keys.x[i]) return true;
                if (s.keys.numeric) {
                    double y = PyFloat_AsDouble(PyList_GetItem(k, 1));
                    if (PyErr_Occurred()) { PyErr_Clear(); return true; }
                    if (y != s.keys.ynum[i]) return true;
                } else {
                    PyObject *oy = PyList_GetItem(k, 1);
                    if (!PyUnicode_Check(oy)) return true;
                    const char *sv = PyUnicode_AsUTF8(oy);
                    if (!sv || s.keys.ystr[i] != sv) return true;
                }
            }
            return false;
        }
    }
    return true;
}

bool parse_template_doc(PyObject *data, const char *id, bool isUser,
                        Template &t, std::string &warn) {
    t = Template();
    t.id = id;
    t.user = isUser;
    t.name = sget(data, "name", id);
    t.category = lower_of(sget(data, "category", "stylized"));
    t.description = sget(data, "description", "");
    t.texture = sget(data, "texture", "");
    t.version = (int)lget(data, "version", 1);
    PyObject *tags = PyDict_GetItemString(data, "tags");
    if (tags && PyList_Check(tags))
        for (Py_ssize_t i = 0; i < PyList_Size(tags); i++) {
            PyObject *o = PyList_GetItem(tags, i);
            if (o && PyUnicode_Check(o)) {
                const char *s = PyUnicode_AsUTF8(o);
                if (s) t.tags.push_back(lower_of(s));
            }
        }
    t.modes = 0;
    PyObject *modes = PyDict_GetItemString(data, "modes");
    if (modes && PyList_Check(modes)) {
        for (Py_ssize_t i = 0; i < PyList_Size(modes); i++) {
            PyObject *o = PyList_GetItem(modes, i);
            if (o && PyUnicode_Check(o)) {
                const char *s = PyUnicode_AsUTF8(o);
                if (s && !strcmp(s, "2d")) t.modes |= 1;
                if (s && !strcmp(s, "3d")) t.modes |= 2;
            }
        }
    }
    if (!t.modes) t.modes = 3;
    std::string w;
    trailpub::validate_block(PyDict_GetItemString(data, "settings"),
                             trailpub::g_reg, t.settings, w);
    if (!w.empty()) warn += "settings: " + w;
    w.clear();
    trailpub::validate_block(PyDict_GetItemString(data, "overrides_2d"),
                             trailpub::g_reg, t.overrides2d, w);
    if (!w.empty()) warn += "overrides_2d: " + w;
    w.clear();
    trailpub::validate_block(PyDict_GetItemString(data, "overrides_3d"),
                             trailpub::g_reg, t.overrides3d, w);
    if (!w.empty()) warn += "overrides_3d: " + w;
    return true;
}

PyObject *template_info_dict(const Template &t) {
    PyObject *tags = PyList_New(t.tags.size());
    if (!tags) return nullptr;
    for (size_t i = 0; i < t.tags.size(); i++)
        PyList_SET_ITEM(tags, i, PyUnicode_FromString(t.tags[i].c_str()));
    PyObject *modes = PyList_New(0);
    if (!modes) { Py_DECREF(tags); return nullptr; }
    if (t.modes & 1) PyList_Append(modes, PyUnicode_FromString("2d"));
    if (t.modes & 2) PyList_Append(modes, PyUnicode_FromString("3d"));
    PyObject *d = Py_BuildValue("{s:s,s:s,s:s,s:s,s:O,s:O,s:s,s:i,s:i}",
                                "id", t.id.c_str(), "name", t.name.c_str(),
                                "category", t.category.c_str(),
                                "description", t.description.c_str(),
                                "tags", tags, "modes", modes,
                                "texture", t.texture.c_str(),
                                "version", t.version, "user", (int)t.user);
    Py_DECREF(tags);
    Py_DECREF(modes);
    return d;
}
