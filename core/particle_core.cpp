constexpr double PI = 3.14159265358979323846;

inline double clamp01(double v) { return v < 0.0 ? 0.0 : (v > 1.0 ? 1.0 : v); }
inline std::string lower_str(const std::string &s) {
    std::string o = s;
    for (char &c : o) c = (char)tolower((unsigned char)c);
    return o;
}

// Canonical shape order (generated contract — mirrors particle_studio.SHAPE_ORDER).
int shape_index(const std::string &s) {
    std::string l = lower_str(s);
    for (int i = 0; i < CARROT_SHAPE_COUNT; i++)
        if (l == CARROT_SHAPE_ORDER[i]) return i;
    return 0;
}

double ease_fn(double t, int ease) {
    t = clamp01(t);
    if (ease == 1) return t * t;
    if (ease == 2) return t * (2 - t);
    if (ease == 3) return t < 0.5 ? 2 * t * t : -1 + (4 - 2 * t) * t;
    return t;
}
inline int ease_enum(const std::string &name) {
    if (name == "ease-in") return 1;
    if (name == "ease-out") return 2;
    if (name == "ease-in-out") return 3;
    return 0;  // "linear" + anything unknown
}

struct RGB { int r = 255, g = 255, b = 255; };
RGB parse_hex(const std::string &c) {
    std::string h = c;
    if (!h.empty() && h[0] == '#') h = h.substr(1);
    if (h.size() == 3) {
        std::string e;
        for (char ch : h) { e += ch; e += ch; }
        h = e;
    }
    if (h.size() < 6) return RGB{};
    try {
        return {(int)std::stoul(h.substr(0, 2), nullptr, 16),
                (int)std::stoul(h.substr(2, 2), nullptr, 16),
                (int)std::stoul(h.substr(4, 2), nullptr, 16)};
    } catch (...) { return RGB{}; }
}

struct Keyframe {
    double dur = 0.5, size = 8, sizeMax = 8, opacity = 255, minSpd = 0, maxSpd = 0;
    // Precomputed at configure() so the per-particle hot loops never touch
    // strings: color parsed once, easing as enum, shape as order index.
    // Values are identical to parsing on the fly (parity-safe).
    int shapeIdx = 0;
    int cr = 255, cg = 255, cb = 255;
    int ease = 0;  // 0 linear, 1 ease-in, 2 ease-out, 3 ease-in-out
};

struct Emitter {
    double flow = 40, maxParticles = 300, reservoir = 50;
    bool burst = false, reverse = false;
    // zone
    std::string zshape = "circle", zmode = "surface";
    double radius = 10, width = 100, height = 60, length = 100, depth = 60, rot = 0;
    // cone
    double direction = 0, directionY = 0, spread = 90;
    // force fields (format 1.1, all off = legacy motion)
    double turbAmount = 0, turbScale = 0.05, turbSpeed = 1.0;
    double vortexStrength = 0;
    double attrX = 0, attrY = 0, attrZ = 0, attrStrength = 0, attrRadius = 200;
    bool hasPlane = false;
    double planeY = 0, planeBounce = 0.5, planeFriction = 0.1;
    bool hasFields = false;  // any accel field or plane active: skip math if false
};

// Trail/ribbon settings (format 1.1 emitter.trails, additive: absent = off).
// Curves/gradients arrive baked as LUTs would be evaluated: the Python side
// bakes 64-sample width + 256-entry gradient tables on change; the core
// stores the same tables parsed from raw keys so both sides agree exactly.
// (Ring-buffer trail simulation itself lands next; settings parse first.)
struct TrailCfg {
    bool enabled = false;
    int maxPoints = 32;
    double lifetime = 1.0, minDist = 4.0, minTime = 0.016;
    bool autodestruct = false;
    double timeScale = 1.0, fadeStop = 0.0;
    double widthStart = 8.0, widthEnd = 1.0, widthMult = 1.0;
    double intensity = 1.0;
    double wlut[64];
    int cr[256], cg[256], cb[256], ca[256];
    int lcr[256], lcg[256], lcb[256], lca[256];
    TrailCfg() {
        for (int i = 0; i < 64; i++) wlut[i] = 1.0;
        for (int i = 0; i < 256; i++) {
            cr[i] = cg[i] = cb[i] = 255; ca[i] = 255;
            lcr[i] = lcg[i] = lcb[i] = 255; lca[i] = 255;
        }
    }
};

// ---- Python dict helpers (borrowed refs, defaults on missing) ----
double dget(PyObject *d, const char *k, double fb) {
    if (!d || !PyDict_Check(d)) return fb;
    PyObject *v = PyDict_GetItemString(d, k);
    if (!v || v == Py_None) return fb;
    double x = PyFloat_AsDouble(v);
    return PyErr_Occurred() ? (PyErr_Clear(), fb) : x;
}
long lget(PyObject *d, const char *k, long fb) {
    if (!d || !PyDict_Check(d)) return fb;
    PyObject *v = PyDict_GetItemString(d, k);
    if (!v || v == Py_None) return fb;
    long x = PyLong_AsLong(v);
    return PyErr_Occurred() ? (PyErr_Clear(), fb) : x;
}
bool bget(PyObject *d, const char *k, bool fb) {
    if (!d || !PyDict_Check(d)) return fb;
    PyObject *v = PyDict_GetItemString(d, k);
    if (!v || v == Py_None) return fb;
    int x = PyObject_IsTrue(v);
    return x < 0 ? (PyErr_Clear(), fb) : (bool)x;
}
std::string sget(PyObject *d, const char *k, const std::string &fb) {
    if (!d || !PyDict_Check(d)) return fb;
    PyObject *v = PyDict_GetItemString(d, k);
    if (!v || v == Py_None) return fb;
    if (PyUnicode_Check(v)) {
        const char *s = PyUnicode_AsUTF8(v);
        return s ? s : fb;
    }
    return fb;
}
